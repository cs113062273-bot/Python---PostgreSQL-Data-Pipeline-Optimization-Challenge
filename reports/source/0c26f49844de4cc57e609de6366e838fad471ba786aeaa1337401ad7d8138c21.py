"""Retire a reproducible six-table JSON verifier cache, never public data."""
import argparse
from datetime import datetime,timezone
import json
from pathlib import Path
from psycopg import sql
from bench.common import ROOT,connect,require_lab,write_report
from pipeline.recipes import ORDER
from tests.equivalence.oracle import protected_schema_signature,sequence_signature


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cohort',required=True)
    p.add_argument('--apply',action='store_true')
    args=p.parse_args();receipt=(ROOT/args.cohort).resolve()
    if not receipt.is_relative_to(ROOT/'reports'):p.error('Use our completed cohort receipt')
    cohort=json.loads(receipt.read_text(encoding='utf8'))
    assert cohort['kind']=='fresh_local_original_service_complete_processing' and cohort.get('summary')
    assert all(r['six_table_fingerprints_equivalent'] and r['counter_reconciliation'] and r['versions']==6 for r in cohort['runs'])
    db=cohort['reference'];assert db in ('lab_1m','lab_100k')
    with connect(db,autocommit=True) as c:
        require_lab(c)
        assert c.info.host in ('127.0.0.1','localhost','::1')
        assert Path(c.execute('SHOW data_directory').fetchone()[0]).resolve()==(ROOT/'.runtime/pgdata').resolve()
        before=protected_schema_signature(c);sequences=sequence_signature(c)
        with c.transaction():
            oid=c.execute("SELECT oid FROM pg_namespace WHERE nspname='challenge_reference'").fetchone()
            if oid is None:print('JSON reference cache already absent',flush=True);return
            assert c.execute("SELECT relname,relkind FROM pg_class WHERE relnamespace=%s ORDER BY relname",(oid[0],)).fetchall()==[(table,'r') for table in sorted(ORDER)]
            columns=c.execute("SELECT c.relname,a.attname,a.atttypid::regtype::text FROM pg_class c JOIN pg_attribute a ON a.attrelid=c.oid WHERE c.relnamespace=%s AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum",(oid[0],)).fetchall()
            assert columns==[(table,'value','jsonb') for table in sorted(ORDER)]
            size=c.execute('SELECT sum(pg_total_relation_size(oid)) FROM pg_class WHERE relnamespace=%s',(oid[0],)).fetchone()[0]
            print('Reproducible JSON verifier cache only:',db,int(size),'bytes; apply=',args.apply,flush=True)
            if args.apply:
                c.execute(sql.SQL('LOCK TABLE '+','.join('{}' for _ in ORDER)+' IN ACCESS EXCLUSIVE MODE NOWAIT').format(*(sql.Identifier('challenge_reference',table) for table in ORDER)))
                c.execute(sql.SQL('DROP TABLE '+','.join('{}' for _ in ORDER)+' RESTRICT').format(*(sql.Identifier('challenge_reference',table) for table in ORDER)))
                c.execute('DROP SCHEMA challenge_reference RESTRICT')
        assert protected_schema_signature(c)==before and sequence_signature(c)==sequences
    if args.apply:
        write_report('reports/retired-json-reference-cache.json',{'timestamp_utc':datetime.now(timezone.utc).isoformat(),'database':db,'schema':'challenge_reference','bytes_removed':int(size),'completed_receipt':str(receipt.relative_to(ROOT)),'public_source_destinations_schema_sequences_untouched':True,'scope':'Only six plain JSON verifier tables removed. Complete original public oracle/source tables and every native benchmark/versioned database remain. New reference-based exact verification uses session-private typed EXCEPT ALL. Historical JSON cache can be regenerated by tests.equivalence.oracle.snapshot from original public results.'})


if __name__=='__main__':main()
