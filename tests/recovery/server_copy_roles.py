"""Native counter/default-ID proof for server-file privilege fallback."""
import os
from pathlib import Path
import tempfile
import uuid

from psycopg import sql
from bench.common import ROOT,connect,write_report
from bench.fixture import create_fixture
from bench.server_copy_probe import run,source_identity
from pipeline.native_copy import MARKER
from pipeline.recipes import ORDER


def main():
    db='lab_server_roles_'+uuid.uuid4().hex[:8];create_fixture(db)
    role='lab_copy_no_files_'+uuid.uuid4().hex[:8]
    parent=(ROOT/'.runtime/server_copy_tests').resolve();parent.mkdir(parents=True,exist_ok=True)
    directory=Path(tempfile.mkdtemp(prefix='roles_',dir=parent)).resolve();assert directory.parent==parent
    with connect(db,autocommit=True) as c:
        c.execute(sql.SQL('CREATE ROLE {} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT').format(sql.Identifier(role)))
    try:
        body='BEGIN; SET LOCAL ROLE '+role+';\nCREATE TEMP TABLE receipts(table_name text,n bigint) ON COMMIT DROP;\n'
        for table in ORDER:body+=f'CREATE TEMP TABLE {table}(id bigint GENERATED BY DEFAULT AS IDENTITY,n integer) ON COMMIT DROP;\n'
        body+=MARKER+'\n'
        for table in ORDER:
            body+=f"\\copy (SELECT n FROM generate_series(1,3) s(n) ORDER BY n) TO '{table}.bin' (FORMAT BINARY)\n\\copy pg_temp.{table}(n) FROM '{table}.bin' (FORMAT BINARY)\nINSERT INTO receipts VALUES('{table}',:'ROW_COUNT'::bigint);\n"
        checks=' UNION ALL '.join(f'SELECT count(*)=3 AND min(id)=1 AND max(id)=3 AS ok FROM pg_temp.{t}' for t in ORDER)
        body+="DO $check$ BEGIN IF EXISTS(SELECT 1 FROM ("+checks+") checked WHERE NOT ok) THEN RAISE EXCEPTION 'Native default identity mismatch'; END IF; END $check$;\nSELECT 'server_roles_receipts='||sum(n)::text FROM receipts;\nCOMMIT;\n"
        argv=[os.environ['CHALLENGE_PSQL'],'-X','-q','-A','-t','-v','ON_ERROR_STOP=1','-d',db]
        result=run(argv,body,cwd=directory,timeout=30)
        assert result.returncode==0,result.stderr
        assert 'server_roles_receipts=18' in result.stdout
        diagnostics=result.local_backend_diagnostics
        assert diagnostics['privilege_fallback_to_client'] and not diagnostics['server_files_used'] and diagnostics['actual_binary_files']==6
        assert all((directory/(t+'.bin')).read_bytes().startswith(b'PGCOPY\n\xff\r\n\0') for t in ORDER)
        with connect(db,autocommit=True) as c:
            assert not c.execute("SELECT rolname FROM pg_auth_members JOIN pg_roles ON roleid=pg_roles.oid WHERE member=%s::regrole",(role,)).fetchall()
        write_report('reports/server-copy-no-file-role-fallback.json',{'kind':'server_file_privilege_fallback_primitive','passed':True,'database':db,'hook_sha256':source_identity(),'six_actual_copy_receipts_total':18,'native_default_identity_three_rows_each':True,'no_server_file_role_granted':True,'diagnostics':diagnostics,'scope':'Small transport primitive only. The role is deliberately unprivileged, TEMP objects drop at commit; not a full managed-role benchmark.'})
        print('No-file-role fallback PASS: six native COPY receipts, 18 rows, native default IDs, no privilege grant',flush=True)
    finally:
        for table in ORDER:(directory/(table+'.bin')).unlink(missing_ok=True)
        directory.rmdir()
        with connect(db,autocommit=True) as c:c.execute(sql.SQL('DROP ROLE {}').format(sql.Identifier(role)))


if __name__=='__main__':main()
