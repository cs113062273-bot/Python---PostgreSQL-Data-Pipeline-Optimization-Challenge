"""Native psql COPY with real command-tag receipts for managed counters.

Binary files are client-side in a private per-batch working directory. Original
constraints, identity defaults and atomic transaction are retained. No server
file privilege, PROGRAM, UDF, manual identity or COPY FREEZE is used.
"""
import re
from pipeline.parallel_normalization import settings_sql,restore_settings_sql

MARKER='-- pipeline native psql copy v1'


def layout_guard_sql():
    """Binary COPY requires the canonical receiving types, not just names.

    A changed timestamp/int width, typmod, collation, identity or extra index /
    constraint selects the exact original INSERT path. This describes the fixed
    organizer schema, never generator values or expected answers.
    """
    from pipeline.upstream import APP
    from pipeline.recipes import ORDER
    from pipeline.bulk_fks import FOREIGN_KEYS
    def lit(value):return "'"+value.replace("'","''")+"'"
    source=(APP/'generate_database.py').read_text(encoding='utf-8')
    expected=[]
    for table in ORDER:
        block=re.search(r'CREATE TABLE public\.'+table+r'\s*\((.*?)\n\)',source,re.S)
        if not block:raise RuntimeError('Unknown original COPY target schema')
        columns=[]
        for line in block[1].splitlines():
            m=re.match(r'\s+([a-z][a-z_0-9]*)\s+(character varying|timestamp without time zone|bigint|smallint|integer|numeric|text|jsonb)\b',line)
            if not m:continue
            name,kind=m.groups()
            identity='d' if 'GENERATED BY DEFAULT AS IDENTITY' in line else ''
            notnull='true' if 'NOT NULL' in line or 'PRIMARY KEY' in line else 'false'
            columns.append((name,kind,identity,notnull))
        if not columns:raise RuntimeError('No canonical COPY columns')
        expected.extend('('+','.join((lit(table),str(n),lit(name),lit(kind),lit(identity),notnull))+')' for n,(name,kind,identity,notnull) in enumerate(columns,1))
    values=','.join(expected)
    relations=','.join("'public."+t+"'::regclass" for t in ORDER)
    indexes=[]
    def index(table,name,columns,unique=True,predicate=None):
        definition='CREATE '+('UNIQUE ' if unique else '')+'INDEX '+name+' ON public.'+table+' USING btree ('+', '.join(columns)+')'+(' WHERE ('+predicate+')' if predicate else '')
        indexes.append('('+','.join(map(lit,(table,name,definition)))+')')
    for table in ORDER:index(table,table+'_pkey',['id_column_1'])
    index('table1','table1_id_column_3_key',['id_column_3'])
    index('table2','table2_id_column_2_integer_column_1_key',['id_column_2','integer_column_1'])
    index('table6','table6_id_column_2_id_column_3_key',['id_column_2','id_column_3'])
    index('table5','table5_id_column_3_not_null_key',['id_column_3'],predicate='id_column_3 IS NOT NULL')
    index('table5','table5_id_column_2_when_id_column_3_null_key',['id_column_2'],predicate='id_column_3 IS NULL')
    fkvalues=','.join('('+','.join(map(lit,row))+')' for row in FOREIGN_KEYS)
    checks=["CHECK (((text_column_1 IS NULL) OR ((text_column_1)::text = ANY ((ARRAY['X'::character varying, 'Y'::character varying, 'Z'::character varying])::text[]))))", "CHECK (((text_column_1 IS NULL) OR ((text_column_1)::text = ANY (ARRAY[('X'::character varying)::text, ('Y'::character varying)::text, ('Z'::character varying)::text]))))"]
    condition=f"""(SELECT count(*) FROM pg_attribute WHERE attrelid IN ({relations}) AND attnum>0 AND NOT attisdropped)={len(expected)}
      AND NOT EXISTS(SELECT 1 FROM (VALUES {values}) e(table_name,ordinal,name,kind,identity_kind,required)
        LEFT JOIN pg_attribute a ON a.attrelid=('public.'||e.table_name)::regclass AND a.attnum=e.ordinal
        WHERE a.attname IS DISTINCT FROM e.name OR format_type(a.atttypid,a.atttypmod) IS DISTINCT FROM e.kind
          OR a.attidentity::text IS DISTINCT FROM e.identity_kind OR a.attnotnull IS DISTINCT FROM e.required
          OR a.attgenerated<>'' OR a.attisdropped
          OR a.attcollation<>CASE WHEN e.kind IN ('text','character varying') THEN 'default'::regcollation ELSE 0::oid END)
      AND (SELECT count(*) FROM pg_index WHERE indrelid IN ({relations}))={len(indexes)}
      AND NOT EXISTS(SELECT 1 FROM (VALUES {','.join(indexes)}) e(table_name,index_name,definition)
        LEFT JOIN pg_class x ON x.relnamespace='public'::regnamespace AND x.relname=e.index_name
        LEFT JOIN pg_index i ON i.indexrelid=x.oid AND i.indrelid=('public.'||e.table_name)::regclass
        WHERE i.indexrelid IS NULL OR NOT i.indisvalid OR NOT i.indisready OR pg_get_indexdef(i.indexrelid) IS DISTINCT FROM e.definition)
      AND (SELECT count(*) FROM pg_constraint WHERE conrelid IN ({relations}))=16
      AND NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid IN ({relations}) AND (condeferrable OR NOT convalidated))
      AND NOT EXISTS(SELECT 1 FROM (VALUES {fkvalues}) e(table_name,constraint_name,definition)
        LEFT JOIN pg_constraint k ON k.conrelid=('public.'||e.table_name)::regclass AND k.conname=e.constraint_name AND k.contype='f'
        WHERE k.oid IS NULL OR NOT k.convalidated OR k.condeferrable OR pg_get_constraintdef(k.oid) IS DISTINCT FROM e.definition)
      AND EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='public.table2'::regclass AND conname='table2_text_column_1_check'
        AND convalidated AND pg_get_constraintdef(oid) IN ({','.join(map(lit,checks))}))
      AND NOT EXISTS(SELECT 1 FROM pg_class WHERE oid IN ({relations}) AND (relkind<>'r' OR relispartition OR relrowsecurity))
      AND NOT EXISTS(SELECT 1 FROM pg_class WHERE oid IN ({relations}) AND NOT pg_has_role(current_user,relowner,'USAGE'))
      AND NOT EXISTS(SELECT 1 FROM pg_inherits WHERE inhrelid IN ({relations}) OR inhparent IN ({relations}))
      AND NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgrelid IN ({relations}) AND NOT tgisinternal)"""
    return "DO $copy_layout$ DECLARE previous_path text:=pg_catalog.current_setting('search_path'); BEGIN PERFORM pg_catalog.set_config('search_path','pg_catalog',true); UPDATE pg_temp.pipeline_normalization_domain SET safe=safe AND ("+condition+"); PERFORM pg_catalog.set_config('search_path',previous_path,true); END $copy_layout$;"


def prepare_receipts_sql():
    return """CREATE TEMP TABLE pipeline_copy_receipts(table_name text PRIMARY KEY,affected_rows bigint NOT NULL CHECK(affected_rows>=0)) ON COMMIT DROP;
SELECT safe AS pipeline_copy_safe FROM pg_temp.pipeline_normalization_domain
\\gset
"""


def single_line_sql(query):
    """Normalize only whitespace outside SQL literals/quoted identifiers.

    The COPY SELECT is bound to the canonical recipes over the work relation;
    scope values stay in the separate ordinary SQL projection, never this line.
    Refuse embedded literal newlines rather than silently changing their value.
    """
    result=[];quote=None;i=0
    while i<len(query):
        ch=query[i]
        if quote:
            if ch in '\r\n':raise RuntimeError('Canonical COPY literal contains a newline')
            result.append(ch)
            if ch==quote:
                if i+1<len(query) and query[i+1]==quote:
                    result.append(query[i+1]);i+=1
                else:quote=None
        elif ch in ("'",'"'):
            quote=ch;result.append(ch)
        elif ch.isspace():
            if result and result[-1]!=' ':result.append(' ')
        else:result.append(ch)
        i+=1
    if quote:raise RuntimeError('Unclosed canonical COPY literal')
    return ''.join(result).strip()


def copy_sql(statement,table):
    m=re.fullmatch(r'INSERT INTO public\.'+re.escape(table)+r'\s*\((.*?)\)\s*(SELECT\s.*?);?',statement,re.S)
    if not m:raise RuntimeError('Unknown protected COPY source')
    columns=','.join(x.strip() for x in m[1].split(','))
    query=m[2].rstrip(';')
    tune='SET LOCAL enable_parallel_hash=off;\n' if table=='table1' else ''
    # \copy opens binary files correctly on Windows as well as Unix. Generic
    # \g redirection can use text-mode output and corrupt the binary signature.
    return MARKER+"\n\\if :pipeline_copy_safe\n"+settings_sql()+'\n'+tune+"\\copy ("+single_line_sql(query)+") TO '"+table+".bin' (FORMAT BINARY)\n"+f"\\copy public.{table} ({columns}) FROM '{table}.bin' (FORMAT BINARY)\n"+f"INSERT INTO pg_temp.pipeline_copy_receipts VALUES('{table}',:'ROW_COUNT'::bigint);\n"+restore_settings_sql()+"\n\\endif\n"


def managed_receipt_sql(managed,statement,table):
    declaration='pgdm_affected_rows bigint;'
    diagnostics='GET DIAGNOSTICS pgdm_affected_rows = ROW_COUNT;'
    if managed.count(statement)!=1 or managed.count(declaration)!=1 or managed.count(diagnostics)!=1:
        raise RuntimeError('Unknown native managed counter boundary')
    # The declaration caches the decision before any fallback INSERT. The
    # fallback GET DIAGNOSTICS immediately follows its actual DML, preserving
    # ROW_COUNT; COPY uses the server's command tag captured by psql.
    replacement=f"""IF pipeline_copy_fast THEN
      SELECT affected_rows INTO STRICT pgdm_affected_rows FROM pg_temp.pipeline_copy_receipts WHERE table_name='{table}';
    ELSE
      {statement};
      {diagnostics}
    END IF"""
    result=managed.replace(diagnostics,'',1)
    result=result.replace(declaration,declaration+'\n    pipeline_copy_fast boolean := (SELECT safe FROM pg_temp.pipeline_normalization_domain);',1)
    return result.replace(statement,replacement,1)
