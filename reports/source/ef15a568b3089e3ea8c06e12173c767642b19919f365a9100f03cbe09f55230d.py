"""Actual native phased COPY, rollback and blocked-input timeout checks."""
import argparse
import os
from pathlib import Path
import tempfile
import time
import uuid

from psycopg import sql

from bench.common import ROOT,connect,write_report
from bench.fixture import create_fixture
from pipeline.checkpoints import source_digest
from pipeline.psql_session import PsqlSession


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',default='reports/recovery-psql-session.json')
    args=parser.parse_args()
    db='lab_psql_session_'+uuid.uuid4().hex[:8];create_fixture(db)
    argv=[os.environ['CHALLENGE_PSQL'],'-h',os.environ.get('PGHOST','127.0.0.1'),'-p',os.environ.get('PGPORT','55432'),'-U',os.environ.get('PGUSER','challenge'),'-d',db,'-f','-']
    results=[];cancelled=[]
    def cancel_backend(pid,application_name,epoch):
        with connect('postgres',autocommit=True,connect_timeout=5) as c:
            # A PID alone is insufficient after a backend exit/reuse. Only
            # terminate this session's exact PID/start instant and database.
            row=c.execute('SELECT pid FROM pg_stat_activity WHERE pid=%s AND datname=%s AND extract(epoch FROM backend_start)=%s::numeric',(pid,db,epoch)).fetchone()
            if row:
                assert c.execute('SELECT pg_terminate_backend(%s)',(pid,)).fetchone()[0]
                cancelled.append(pid)
    def absent(schema):
        with connect(db,autocommit=True) as c:assert c.execute('SELECT to_regnamespace(%s)',(schema,)).fetchone()[0] is None
    parent=(ROOT/'.runtime/psql_session_tests').resolve();parent.mkdir(parents=True,exist_ok=True)
    directory=Path(tempfile.mkdtemp(prefix='phase_',dir=parent)).resolve()
    assert directory.parent==parent
    with connect(db,autocommit=True) as c:before=source_digest(c,['group001'])
    try:
        schema='native_phase_'+uuid.uuid4().hex[:8]
        with PsqlSession(argv,cwd=directory,cancel_backend=cancel_backend) as session:
            literal='a\nb\r\nc\rd'
            assert session.send("SELECT encode(convert_to('"+literal+"','UTF8'),'hex');").strip()==literal.encode().hex()
            first=session.send(f"""BEGIN ISOLATION LEVEL REPEATABLE READ;
                CREATE SCHEMA {schema};
                CREATE TABLE {schema}.src(n bigint,payload text,stamp timestamptz);
                CREATE TABLE {schema}.dst(id bigint GENERATED BY DEFAULT AS IDENTITY,n bigint,payload text,stamp timestamptz);
                INSERT INTO {schema}.src VALUES(1,chr(20013)||chr(25991)||chr(10)||chr(13)||chr(9)||chr(92),timestamptz '2024-11-03 01:30:00.123456-04'),(2,NULL,NULL),(3,'',timestamptz '2020-01-01 00:00:00+00');
                SELECT true AS copy_safe
\\gset
""")
            assert not first.strip()
            session.send(f"\\if :copy_safe\n\\copy (SELECT n,payload,stamp FROM {schema}.src ORDER BY n) TO 'table1.bin' (FORMAT BINARY)\n\\endif\n")
            session.send(f"\\if :copy_safe\n\\copy {schema}.dst(n,payload,stamp) FROM 'table1.bin' (FORMAT BINARY)\n\\endif\n")
            # Phase-end \\echo must preserve the native COPY command tag used
            # by the next phase's managed row-count receipt.
            assert session.send("SELECT 'copy_rows='||:'ROW_COUNT';").strip()=='copy_rows=3'
            assert session.send("SELECT false AS skip\n\\gset\n\\if :skip\n\\copy missing_table FROM 'missing.bin'\n\\endif\nSELECT 'skip_ok';").strip()=='skip_ok'
            session.send('COMMIT;')
        binary=(directory/'table1.bin').read_bytes()
        assert binary.startswith(b'PGCOPY\n\xff\r\n\0')
        with connect(db,autocommit=True) as c:
            assert not c.execute(f'SELECT EXISTS((SELECT n,payload,stamp FROM {schema}.src EXCEPT ALL SELECT n,payload,stamp FROM {schema}.dst) UNION ALL (SELECT n,payload,stamp FROM {schema}.dst EXCEPT ALL SELECT n,payload,stamp FROM {schema}.src))').fetchone()[0]
            assert c.execute(f'SELECT count(*),count(DISTINCT id),min(id),max(id) FROM {schema}.dst').fetchone()==(3,3,1,3)
            c.execute(sql.SQL('DROP TABLE {},{} RESTRICT').format(sql.Identifier(schema,'src'),sql.Identifier(schema,'dst')))
            c.execute(sql.SQL('DROP SCHEMA {} RESTRICT').format(sql.Identifier(schema)))
        results.append({'name':'native_phased_binary_copy_and_real_command_tag','passed':True,'rows':3,'unicode_cr_lf_tab_backslash_and_null_preserved':True,'sql_literal_line_endings_preserved':True,'native_identity_defaults':True,'if_gset_and_false_branch':True})
        schema='native_eof_'+uuid.uuid4().hex[:8]
        with PsqlSession(argv,cwd=directory,cancel_backend=cancel_backend) as session:
            session.send(f'BEGIN; CREATE SCHEMA {schema}; CREATE TABLE {schema}.pending(v int); INSERT INTO {schema}.pending VALUES(1);')
        absent(schema)
        results.append({'name':'clean_eof_rolls_back_uncommitted_ddl_and_data','passed':True})
        schema='native_error_'+uuid.uuid4().hex[:8]
        try:
            with PsqlSession(argv,cwd=directory,cancel_backend=cancel_backend) as session:
                session.send(f'\\set VERBOSITY verbose\nBEGIN; CREATE SCHEMA {schema}; SELECT 1/0;')
        except RuntimeError as error:assert '22012' in str(error) and 'division by zero' in str(error)
        else:raise AssertionError('Native SQL error was not propagated')
        absent(schema)
        results.append({'name':'actual_sqlstate_and_transaction_rollback','passed':True,'sqlstate':'22012'})
        for large_input in (False,True):
            schema='native_timeout_'+uuid.uuid4().hex[:8]
            with PsqlSession(argv,cwd=directory,cancel_backend=cancel_backend) as session:
                session.send(f"BEGIN; CREATE SCHEMA {schema}; SET application_name='authored_phase_name';")
                count=len(cancelled);started=time.monotonic()
                try:session.send('SELECT pg_sleep(60);\n'+('SELECT 1;\n'*20000 if large_input else ''),timeout=.2)
                except TimeoutError:pass
                else:raise AssertionError('Native phase did not time out')
                elapsed=time.monotonic()-started
                assert elapsed<5 and len(cancelled)==count+1 and not session.abort_errors
            absent(schema)
            results.append({'name':'blocked_input_pipe_timeout' if large_input else 'native_query_timeout','passed':True,'elapsed_seconds':elapsed,'exact_backend_identity_verified_before_termination':True})
        with connect(db,autocommit=True) as c:
            assert source_digest(c,['group001'])==before
            assert c.execute('SELECT sum(n) FROM (SELECT count(*) n FROM public.table1 UNION ALL SELECT count(*) FROM public.table2 UNION ALL SELECT count(*) FROM public.table3 UNION ALL SELECT count(*) FROM public.table4 UNION ALL SELECT count(*) FROM public.table5 UNION ALL SELECT count(*) FROM public.table6) s').fetchone()[0]==0
        write_report(args.output,{'kind':'phased_native_psql_primitive_not_full_chunk_protocol','database':db,'passed':True,'cases':results,'source_and_original_destinations_unchanged':True,'scope':'Actual psql process and binary files; no SQL/metacommand interpreter, no pure-Python data-row serialization. This is a transport primitive, not final bounded-stage/checkpoint integration.'})
        print('Native phased psql:',len(results),'cases PASS',flush=True)
    finally:
        # Fixed basename only, no recursive deletion or user path expansion.
        (directory/'table1.bin').unlink(missing_ok=True)
        directory.rmdir()


if __name__=='__main__':main()
